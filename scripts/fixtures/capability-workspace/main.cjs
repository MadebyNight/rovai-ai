const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { isAbsolute, join, dirname } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData] = process.argv.slice(2)
assert.ok(isAbsolute(renderer) && isAbsolute(userData))
mkdirSync(userData, { recursive: true })
app.setPath('userData', userData)
app.setPath('sessionData', join(userData, 'session'))
// This fixture mounts production components against an in-memory bridge. No Core or Runtime runs.
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: process.platform === 'linux', width: 1440, height: 920, useContentSize: true, ...(process.platform === 'darwin' ? { titleBarStyle: 'hidden', trafficLightPosition: { x: 12, y: 14 } } : {}), webPreferences: { contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false } })
  window.webContents.on('console-message', event => console.error(event.message))
  const run = code => window.webContents.executeJavaScript(code, true)
  const settle = () => run('window.capabilityTest.settle()')
  const snapshot = async () => { await settle(); return run('window.capabilityTest.snapshot()') }
  const key = async (keyCode, modifiers = []) => {
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode, modifiers })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode, modifiers })
    await settle()
  }
  const click = async label => {
    const point = await run(`(() => {
      const b = [...document.querySelectorAll('button')].find(b => b.getBoundingClientRect().width > 0 && (b.textContent.trim().replace(/\\s+/g, ' ') === ${JSON.stringify(label)} || b.getAttribute('aria-label') === ${JSON.stringify(label)} || b.getAttribute('title') === ${JSON.stringify(label)} || (b.matches('.rebuilt-skill-row') && b.querySelector('strong')?.textContent === ${JSON.stringify(label)})))
      if (!b) throw Error('Missing button ' + ${JSON.stringify(label)})
      if (b.closest('.capability-workspace') && getComputedStyle(b).getPropertyValue('-webkit-app-region') !== 'no-drag') throw Error('Button is inside a native window drag region: ' + ${JSON.stringify(label)})
      b.scrollIntoView({ block: 'nearest' })
      const r = b.getBoundingClientRect()
      const hit = document.elementFromPoint(r.x+r.width/2, r.y+r.height/2)
      if (!hit || !b.contains(hit)) throw Error('Button ' + ${JSON.stringify(label)} + ' is covered by ' + hit?.className)
      return { x: Math.round(r.x + r.width / 2), y: Math.round(r.y + r.height / 2) }
    })()`)
    const zoom = window.webContents.getZoomFactor()
    point.x = Math.round(point.x * zoom)
    point.y = Math.round(point.y * zoom)
    window.webContents.sendInputEvent({ type: 'mouseMove', ...point })
    window.webContents.sendInputEvent({ type: 'mouseDown', ...point, button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseUp', ...point, button: 'left', clickCount: 1 })
    return snapshot()
  }
  const edit = async text => { await run(`(() => { const n=[...document.querySelectorAll('textarea')].find(n=>n.getBoundingClientRect().width>0); Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(n, ${JSON.stringify(text)}); n.dispatchEvent(new Event('input',{bubbles:true})) })()`); await settle() }
  const draft = () => run("[...document.querySelectorAll('textarea')].find(n=>n.getBoundingClientRect().width>0)?.value")
  const capture = async name => writeFileSync(join(dirname(userData), name + '.png'), (await window.webContents.capturePage()).toPNG())
  const checkUnsupportedLayout = async () => {
    const rows = await run(`(() => {
      return [...document.querySelectorAll('.capability-import-other-item')].map(row => {
        const heading = row.querySelector('.capability-import-other-heading'), issue = row.querySelector('.capability-note')
        return { issueBelowHeading: !issue || issue.getBoundingClientRect().top >= heading.getBoundingClientRect().bottom,
          overflow: row.scrollWidth > row.clientWidth }
      })
    })()`)
    assert.ok(rows.length >= 2)
    assert.ok(rows.every(row => row.issueBelowHeading), 'Unsupported import issues must appear below the name and source, not squeezed into the same row')
    assert.ok(rows.every(row => !row.overflow), 'Unsupported import rows must wrap within the detail pane')
  }
  try {
    await window.loadFile(renderer)
    await run("localStorage.clear()")
    await new Promise(resolve => { window.webContents.once('did-finish-load', resolve); window.reload() })
    window.webContents.setZoomFactor(1)
    let state = await snapshot()
    await require('./splitter.cjs')({ run, click, key, settle, window })
    await require('./native-skills.cjs')({ run, click, key, settle, capture, snapshot, window })
    await click('MCP')
    state = await snapshot()
    assert.ok(state.text.includes('配置 JSON'))
    assert.ok(state.text.includes('待配置：环境变量 DOCS_TOKEN 在 MCP 启动环境中不可用。'))
    assert.ok(state.text.includes('受影响字段：env.API_TOKEN'))
    assert.ok((await draft()).includes('********'), 'Details show a mask rather than the stored credential')
    await capture('mcp-day-wide')
    assert.equal(await run("window.capabilityTest.requests.filter(r => r.method === 'mcp.servers.reveal').length"), 0, 'Listing never reveals credentials')
    await click('显示疑似凭证')
    assert.ok((await draft()).includes('fixture-env-credential'), 'Explicit reveal restores env values')
    const modified = (await draft()).replace('"docs"', '"renamed-docs"')
    await edit(modified)
    await click('隐藏疑似凭证')
    assert.ok(!(await draft()).includes('fixture-env-credential'))
    await click('显示疑似凭证')
    assert.ok((await draft()).includes('"renamed-docs"'), 'Revealing preserves unrelated unsaved edits')
    await edit((await draft()) + ',')
    await click('隐藏疑似凭证')
    assert.equal(await draft(), '', 'Malformed drafts can always be concealed')
    assert.ok(await run("document.querySelector('[aria-label=\"MCP 配置 JSON\"]').readOnly"))
    await click('显示疑似凭证')
    assert.ok((await draft()).endsWith(','))
    await click('放弃更改')
    await run('window.capabilityTest.holdReveal()')
    await click('显示疑似凭证')
    await edit((await draft()).replace('"docs"', '"edited-during-reveal"'))
    await run('window.capabilityTest.releaseReveal()')
    await settle()
    assert.ok((await draft()).includes('edited-during-reveal'), 'A pending reveal preserves edits made while awaiting the private read')
    await click('放弃更改')
    await click('Playwright')
    await click('显示疑似凭证')
    assert.ok((await draft()).includes('Bearer fixture-header-credential'), 'Authorization prefixes survive reveal')
    await click('隐藏疑似凭证')
    assert.ok(!(await draft()).includes('fixture-header-credential'))
    assert.ok((await draft()).includes('  cn  '), 'Non-credential header whitespace remains visible')
    await run('window.capabilityTest.holdReveal()')
    await click('显示疑似凭证')
    await click('docs')
    await run('window.capabilityTest.releaseReveal()')
    await settle()
    assert.ok(!(await draft()).includes('fixture-header-credential'), 'A late reveal cannot reach a different selected MCP')
    await click('清空')
    assert.equal(await run("document.querySelectorAll('.capability-member-choice[aria-pressed=true]').length"), 0)
    await click('沐瓦')
    assert.equal(await run("document.querySelectorAll('.capability-member-choice[aria-pressed=true]').length"), 1)
    assert.equal(await run("window.capabilityTest.requests.at(-1).method"), 'mcp.servers.setMembers')
    const json = '{\n  "mcpServers": {"docs": {"command": "node", "args": ["draft.mjs"]}}\n}'
    await edit(json)
    // Native pointer drag must preserve the editor node and unsaved draft.
    const point = await run("(() => { const n=[...document.querySelectorAll('[role=separator]')].find(n=>n.getBoundingClientRect().width>0); const r=n.getBoundingClientRect(); return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+80)} })()")
    window.webContents.sendInputEvent({ type: 'mouseMove', ...point })
    window.webContents.sendInputEvent({ type: 'mouseDown', ...point, button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseMove', x: point.x + 65, y: point.y, button: 'left', modifiers: ['leftButtonDown'] })
    window.webContents.sendInputEvent({ type: 'mouseUp', x: point.x + 80, y: point.y, button: 'left', clickCount: 1 })
    state = await snapshot()
    assert.equal(state.list.width, 400)
    assert.equal(await draft(), json)
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Right' })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Right' })
    assert.equal((await snapshot()).list.width, 408, 'Keyboard provides a drag alternative')
    await run("[...document.querySelectorAll('[role=separator]')].find(n=>n.getBoundingClientRect().width>0).dispatchEvent(new MouseEvent('dblclick',{bubbles:true}))")
    assert.equal((await snapshot()).list.width, 320, 'Double click restores the default')
    await click('Skills')
    await click('MCP')
    assert.notEqual(await draft(), json, 'Leaving the page discards unsaved edits')
    await edit(json)
    await run('window.capabilityTest.conflict()')
    await click('保存')
    assert.ok((await snapshot()).text.includes('配置已更新'))
    assert.equal(await draft(), json, 'CAS conflict preserves unsaved JSON')
    await click('重新载入')
    await edit(json)
    await click('保存')
    assert.equal(await run("document.querySelector('.capability-save-action').disabled"), true, 'Successful save clears the draft')
    const positions = await run("(() => { const heading=[...document.querySelectorAll('.capability-library-heading')].find(n=>n.getBoundingClientRect().width>0); const add=heading.querySelector('button'),imp=heading.querySelector('[aria-label=\"从本机导入 MCP\"]');return {add:add.getBoundingClientRect().y,import:imp.getBoundingClientRect().y} })()")
    assert.equal(positions.add, positions.import, 'Add and import share the left heading row')
    await click('从本机导入 MCP')
    assert.ok((await snapshot()).text.includes('local-tools'))
    await run("document.querySelectorAll('.capability-import-other').forEach(d=>d.open=true)")
    await settle()
    await capture('mcp-import-unsupported')
    await checkUnsupportedLayout()
    assert.equal(await run("document.querySelectorAll('.capability-import-issues li').length"), 2, 'Repeated issue reasons are grouped per candidate')
    assert.equal(await run("document.querySelectorAll('.capability-import-issue-fields code').length"), 3, 'All affected fields remain available')
    assert.ok(!(await snapshot()).text.includes('Unrecognized field'))
    assert.equal(await run("document.querySelectorAll('.capability-draft').length"), 0, 'Import creates no list placeholder')
    await click('添加')
    assert.equal(await run("document.querySelectorAll('.capability-import-items').length"), 0)
    await edit('discard-this-new-config')
    await click('从本机导入 MCP')
    await click('添加')
    assert.ok(!(await draft()).includes('discard-this-new-config'), 'A new add form starts fresh')
    await click('从本机导入 MCP')
    await run("document.querySelector('.capability-import-pick').click()")
    await settle()
    await capture('mcp-import-day')
    const cardPoint = await run("(() => {const r=document.querySelector('.capability-import-origins').getBoundingClientRect();return {x:Math.round(r.x+20),y:Math.round(r.y+8)}})()")
    for (const selected of ['false', 'true']) {
      window.webContents.sendInputEvent({ type: 'mouseMove', ...cardPoint })
      window.webContents.sendInputEvent({ type: 'mouseDown', ...cardPoint, button: 'left', clickCount: 1 })
      window.webContents.sendInputEvent({ type: 'mouseUp', ...cardPoint, button: 'left', clickCount: 1 })
      await settle()
      assert.equal(await run("document.querySelector('.capability-import-item').dataset.selected"), selected, 'The source area toggles the whole card')
    }
    assert.equal(await run("document.querySelectorAll('.capability-import-item').length"), 6, 'Same-name runtime candidates are one choice')
    assert.equal(await run("document.querySelector('.capability-import-origins').children.length"), 2)
    await click('查看 local-tools 配置')
    assert.equal(await run("document.querySelector('.capability-import-item').dataset.selected"), 'true', 'Expanding a config does not toggle its selection')
    assert.ok((await draft()).includes('"node"'), 'The first runtime definition remains the editable import source')
    assert.ok((await snapshot()).text.includes('来自 Codex'))
    await capture('mcp-import-config-day')
    await click('收起 local-tools 配置')
    await run("document.querySelectorAll('.capability-import-other').forEach(d=>d.open=true)")
    for (const theme of ['day', 'night']) {
      await run(`document.documentElement.dataset.theme=${JSON.stringify(theme)}`)
      for (const width of [1040, 1760, 2560]) {
        window.setContentSize(width, 920)
        await settle()
        await checkUnsupportedLayout()
        await capture(`mcp-import-${theme}-${width}`)
        if (width === 1040) {
          await run("document.querySelector('.capability-import-other').scrollIntoView({block:'start'})")
          await settle()
          await capture(`mcp-import-limits-${theme}-${width}`)
          await run("document.querySelectorAll('.capability-detail-scroll').forEach(n=>n.scrollTop=0)")
        }
      }
    }
    window.setContentSize(1440, 920)
    await run("document.documentElement.dataset.theme='day'")
    await settle()
    await click('导入 1 项')
    assert.ok((await snapshot()).text.includes('local-tools'))
    assert.equal(await run("window.capabilityTest.requests.filter(r=>r.method==='mcp.import.commit').at(-1).params.selections[0].candidateId"), 'import-1', 'Commit preserves the first candidate identity')
    await click('添加')
    await edit('{secret-do-not-echo')
    await click('添加 MCP')
    const alert = await run("[...document.querySelectorAll('[role=alert]')].find(n=>n.getBoundingClientRect().width>0)?.innerText")
    assert.ok(alert.includes('JSON 格式不正确'))
    assert.ok(!alert.includes('secret-do-not-echo'))
    await edit('{"mcpServers":{"new-connection":{"command":"node"}}}')
    await click('添加 MCP')
    assert.ok((await snapshot()).text.includes('new-connection'))
    await click('删除 MCP')
    assert.equal((await snapshot()).dialogs, 1)
    assert.equal(await run('document.activeElement.textContent'), '取消')
    await run('window.capabilityTest.changeMcpWhileDeleting()')
    await settle()
    assert.ok(await run("document.querySelector('[role=dialog]').textContent.includes('new-connection')"), 'The confirmation stays bound to its original target')
    await click('确认删除')
    assert.ok(await run("document.querySelector('[role=dialog] [role=alert]').textContent.includes('配置已更新')"))
    assert.ok((await snapshot()).text.includes('updated-connection'), 'A stale confirmation must not delete the newer configuration')
    await click('取消')
    assert.notEqual(await run('document.activeElement.getAttribute("aria-label")'), '删除 MCP')
    await click('删除 MCP')
    await capture('mcp-delete-dialog-day')
    await key('Escape')
    assert.equal((await snapshot()).dialogs, 0)
    assert.notEqual(await run('document.activeElement.getAttribute("aria-label")'), '删除 MCP')
    await click('删除 MCP')
    await run('window.capabilityTest.holdDelete()')
    await click('确认删除')
    await key('Escape')
    assert.equal((await snapshot()).dialogs, 1)
    await run('window.capabilityTest.releaseDelete()')
    await settle()
    assert.equal((await snapshot()).dialogs, 0)
    assert.ok(!(await snapshot()).text.includes('updated-connection'))
    for (const theme of ['day', 'night']) {
      await run(`document.documentElement.dataset.theme=${JSON.stringify(theme)}`)
      for (const width of [1040, 2560]) {
        window.setContentSize(width, width === 1040 ? 700 : 1440)
        state = await snapshot()
        assert.equal(state.overflow, false)
        assert.ok(state.detail.width >= 360)
        await capture(`mcp-${theme}-${width}`)
      }
    }
    window.setContentSize(1040, 700)
    await settle()
    await click('MCP')
    await click('添加')
    assert.ok((await snapshot()).text.includes('添加 MCP'), 'MCP Add works in the minimum night window')
    await click('从本机导入 MCP')
    assert.ok((await snapshot()).text.includes('local-tools'), 'MCP Import works in the minimum night window')
    await run("document.querySelectorAll('.capability-import-other').forEach(d=>d.open=true)")
    await settle()
    await checkUnsupportedLayout()
    await click('取消')
    await click('删除 MCP')
    await capture('mcp-delete-dialog-night-minimum')
    await click('取消')
    window.webContents.setZoomFactor(1)
    window.setContentSize(1440, 920)
    await click('MCP')
    await run('window.capabilityTest.resetMcp(true)')
    await settle()
    assert.ok((await snapshot()).text.includes('暂时无法读取 MCP 配置'))
    assert.equal(await run("document.querySelectorAll('.mcp-first-connection').length"), 0, 'A failed read cannot masquerade as an empty library')
    await run('window.capabilityTest.restoreConfigRead()')
    await click('重试')
    assert.equal((await snapshot()).list.width, 0)
    assert.ok((await snapshot()).text.includes('添加第一个 MCP'))
    assert.equal(await run("document.querySelector('[data-empty-library=true] .capability-divider-rail')"), null)
    await capture('mcp-empty-night')
    await click('添加配置')
    assert.equal((await snapshot()).list.width, 0, 'First add keeps a single pane')
    await click('取消')
    await click('从本机导入 MCP')
    assert.equal((await snapshot()).list.width, 0, 'First import keeps a single pane')
    await click('取消')
    window.webContents.setZoomFactor(2)
    await settle()
    assert.ok((await snapshot()).detail.width > 0, 'The empty guide remains visible in compact mode')
    assert.ok((await snapshot()).text.includes('添加第一个 MCP'))
    await capture('mcp-empty-night-zoom')
    window.webContents.setZoomFactor(1)
    await run("document.documentElement.dataset.theme='day'")
    await settle()
    await capture('mcp-empty-day')
    await click('添加配置')
    await edit('{"mcpServers":{"first-connection":{"command":"node"}}}')
    await click('添加 MCP')
    assert.ok((await snapshot()).list.width > 0, 'Saving the first MCP restores the normal split workspace')
    assert.ok((await snapshot()).text.includes('first-connection'))
    console.log(JSON.stringify({ ok: true }))
    window.destroy(); app.quit()
  } catch (error) { console.error(error); await capture('failure'); app.exit(1) }
}).catch(error => { console.error(error); app.exit(1) })
