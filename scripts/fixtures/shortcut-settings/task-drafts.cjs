const assert = require('node:assert/strict')
module.exports = async ({ run, settle, click, capture }) => {
  const act = async code => { await run(code); await settle() }
  const field = label => `[...document.querySelectorAll('.task-field')].find(e=>e.querySelector('span')?.textContent===${JSON.stringify(label)})?.querySelector('input,textarea,select')`
  const fill = async (label, value) => {
    assert.equal(await run(`${field(label)}?.disabled`), false, `${label} is editable`)
    await act(`(()=>{const e=${field(label)};Object.getOwnPropertyDescriptor(Object.getPrototypeOf(e),'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event(e.tagName==='SELECT'?'change':'input',{bubbles:true}))})()`)
  }
  const value = label => run(`${field(label)}?.value`)
  const toggle = async enabled => act(`window.taskDraftTest.tasks(${enabled})`)
  const reopen = async () => { await toggle(false); assert.equal(await run('!!document.querySelector(".task-panel,.task-editor-dialog,.task-cancel-dialog")'), false); await toggle(true) }
  const create = () => click('.task-new-button')
  const lastRequest = () => run('window.taskDraftTest.calls().at(-1).params')
  const assertPending = async () => {
    const count = await run('window.taskDraftTest.calls().length')
    assert.equal(await run('document.querySelector(".task-submit").disabled'), true)
    assert.equal(await run('document.querySelector(".task-submit").textContent'), '正在保存…')
    await click('.task-submit')
    await act('document.querySelector(".task-editor").dispatchEvent(new Event("submit",{bubbles:true,cancelable:true}))')
    assert.equal(await run('window.taskDraftTest.calls().length'), count, 'Recovered pending draft cannot send another command')
  }
  const edit = async (id = 'task-one') => { await click(`[data-task-id="${id}"]`); await click('.task-detail-actions button') }
  await act('window.shortcutTest.tasks(true);window.shortcutTest.screen("drafts")')
  await create(); await fill('标题', '未提交的新任务'); await fill('责任范围与要求', '长描述\n第二段');
  const assignee = await run('window.taskDraftTest.assignee'); await fill('负责人', assignee)
  await reopen(); assert.equal(await run('window.taskDraftTest.calls().length'), 0, 'Disable never submits local input')
  await act('window.taskDraftTest.scope(0,"another-thread")'); await create(); assert.equal(await value('标题'), '', 'Threads do not share new drafts')
  await act('window.taskDraftTest.scope(1)'); await create(); assert.equal(await value('标题'), '', 'Hosts do not share new drafts')
  await fill('标题', 'Host B 草稿')
  await act('window.taskDraftTest.scope(0)'); await create()
  assert.equal(await value('标题'), '未提交的新任务'); assert.equal(await value('责任范围与要求'), '长描述\n第二段'); assert.equal(await value('负责人'), assignee)
  await act('window.taskDraftTest.result("rejected")'); await click('.task-submit')
  const rejectedRequest = await lastRequest()
  assert(await run('!!document.querySelector(".task-form-error")'))
  await reopen(); await create(); assert.equal(await value('标题'), '未提交的新任务', 'Rejected saves retain input')
  await act('window.taskDraftTest.result("pending")'); await click('.task-submit'); await reopen(); await create()
  assert.notEqual((await lastRequest()).commandId, rejectedRequest.commandId, 'A definitive rejection permits a new attempt')
  await assertPending()
  const recoveredPending = await run('document.querySelector(".task-submit").disabled')
  await act('window.taskDraftTest.scope(1)'); await create()
  assert.equal(await run('document.querySelector(".task-submit").disabled'), false, 'Pending submission is Host scoped')
  await act('window.taskDraftTest.scope(0)'); await create(); await assertPending()
  await act('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
  await capture('task-draft-pending-recovered')
  await act('window.taskDraftTest.finish("applied")')
  const recoveredClosed = await run('!document.querySelector(".task-editor-dialog")')
  await reopen(); await create()
  assert.deepEqual({ pending: recoveredPending, closed: recoveredClosed, title: await value('标题') },
    { pending: true, closed: true, title: '' }, 'Restoration preserves pending state and settles the unchanged draft')
  await fill('标题', '第二份新任务'); await fill('负责人', assignee)
  await act('window.taskDraftTest.result("pending")'); await click('.task-submit'); await reopen(); await create(); await fill('标题', '重开后继续输入')
  await act('window.taskDraftTest.finish("applied")'); await reopen(); await create()
  assert.equal(await value('标题'), '重开后继续输入', 'Old save completion cannot erase newer recovered input')
  await click('.task-submit'); await reopen(); await create(); assert.equal(await value('标题'), '', 'Successful save clears its draft')
  await fill('标题', '回执未知'); await fill('负责人', assignee)
  await act('window.taskDraftTest.result("pending")'); await click('.task-submit'); await toggle(false)
  await act('window.taskDraftTest.finish("unknown")'); await toggle(true); await create()
  assert.equal(await run('document.querySelector(".task-submit").disabled'), false, 'Transport failure releases pending state')
  assert.equal(await run('document.querySelector(".task-form-error")?.textContent'), '保存回执未收到', 'Unknown result survives unmount')
  const unknownRequest = await lastRequest(); await click('.task-submit')
  assert.deepEqual(await lastRequest(), unknownRequest, 'Unchanged unknown retry reuses the exact command ID and payload')
  await reopen(); await create(); assert.equal(await value('标题'), '')
  await fill('标题', '未知后修改前'); await fill('负责人', assignee)
  await act('window.taskDraftTest.result("unknown")'); await click('.task-submit')
  const beforeEdit = await lastRequest(); await reopen(); await create(); await fill('标题', '未知后修改后'); await click('.task-submit')
  assert.notEqual((await lastRequest()).commandId, beforeEdit.commandId, 'Changed input must not reuse another payload identity')
  assert.equal((await lastRequest()).title, '未知后修改后')
  await create(); await fill('标题', '隐藏期间保存成功'); await fill('负责人', assignee)
  await act('window.taskDraftTest.result("pending")'); await click('.task-submit'); await toggle(false)
  await act('window.taskDraftTest.finish("applied")'); await toggle(true); await create()
  assert.equal(await value('标题'), '', 'Success clears its draft even without a mounted editor')
  await act('window.taskDraftTest.scope(1)'); await create(); assert.equal(await value('标题'), 'Host B 草稿')
  await act('window.taskDraftTest.scope(0)'); await edit()
  await fill('标题', '修改的标题'); await fill('状态', 'blocked'); await fill('阻塞原因', '等待确认'); await fill('负责人', '')
  await reopen(); await edit('task-two'); assert.equal(await value('标题'), '第二项任务', 'Task identities do not share edit drafts')
  await reopen(); await act('window.taskDraftTest.description("远端新说明")'); await edit()
  assert.equal(await value('标题'), '修改的标题'); assert.equal(await value('责任范围与要求'), '原说明'); assert.equal(await value('状态'), 'blocked'); assert.equal(await value('阻塞原因'), '等待确认'); assert.equal(await value('负责人'), '')
  await capture('task-draft-recovered')
  await fill('负责人', assignee); await act('window.taskDraftTest.result("pending")'); await click('.task-submit')
  await reopen(); await edit(); await assertPending(); await act('window.taskDraftTest.finish("applied")')
  assert.equal(await run('!!document.querySelector(".task-editor-dialog")'), false, 'Recovered update settles in the current editor')
  const patch = await run('window.taskDraftTest.calls().at(-1).params')
  assert.equal(patch.taskId, 'task-one'); assert.equal(patch.title, '修改的标题'); assert.equal(patch.blockedReason, '等待确认')
  assert.equal(Object.hasOwn(patch, 'description'), false, 'Recovered edit base prevents overwriting an unchanged field with stale input')
  await reopen(); await edit(); assert.equal(await value('标题'), '原任务'); assert.equal(await value('责任范围与要求'), '远端新说明')
  await fill('状态', 'completed'); await fill('完成摘要', '完成说明草稿'); await reopen(); await edit(); assert.equal(await value('完成摘要'), '完成说明草稿')
  await reopen(); await click('[data-task-id="task-one"]'); await click('.task-cancel-action'); await fill('取消原因', '取消说明草稿')
  await reopen(); await click('[data-task-id="task-one"]'); await click('.task-cancel-action'); assert.equal(await value('取消原因'), '取消说明草稿')
  await act('window.taskDraftTest.result("pending")'); await click('.task-cancel-dialog .danger-button')
  const cancelCalls = await run('window.taskDraftTest.calls().length')
  await reopen(); await click('[data-task-id="task-one"]'); await click('.task-cancel-action')
  assert.equal(await run('document.querySelector(".task-cancel-dialog .danger-button").disabled'), true)
  await click('.task-cancel-dialog .danger-button'); assert.equal(await run('window.taskDraftTest.calls().length'), cancelCalls)
  await act('window.taskDraftTest.finish("applied")'); assert.equal(await run('!!document.querySelector(".task-cancel-dialog")'), false)
  await reopen(); await click('[data-task-id="task-one"]'); await click('.task-cancel-action'); assert.equal(await value('取消原因'), '')
  await act('window.shortcutTest.screen("settings")')
  console.log('Task drafts: recovered pending blocks duplicate commands; unchanged success clears/closes; newer edits survive; unknown retry preserves exact command; Host/Thread/Task isolation, updates and cancellation passed')
}
