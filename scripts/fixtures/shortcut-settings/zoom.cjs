const assert = require('node:assert/strict')
module.exports = async ({ window, run, settle, click, key, text, platform, primary, store, input, defaults, zoomChanges }) => {
  await run(`window.shortcutTest.screen('settings'); window.shortcutTest.save(${JSON.stringify(defaults)})`); await settle()
  await click('[data-edit="tasks"]')
  window.webContents.setZoomFactor(1.25)
  await key('0', [primary, 'shift'])
  assert(input.isRecording())
  assert.equal(window.webContents.getZoomFactor(), 1.25, 'Recording bypasses the production zoom handler')
  assert.match(await text(), /恢复默认缩放/, 'Shift+0 is rejected before it can be saved')
  assert(await run('document.querySelector(".shortcut-inline-actions .primary-button").disabled'))
  assert.equal(store.get().preferences.bindings.tasks, 'Mod+4')
  const invalid = structuredClone(defaults); invalid.bindings.tasks = 'Mod+Shift+0'
  await assert.rejects(store.save({ expectedRevision: store.get().revision, preferences: invalid }), /快捷键设置无效/)
  await key('T', ['alt'])
  assert(await run('document.querySelector(".shortcut-validation-error") === null'))
  await click('.shortcut-inline-actions .primary-button')
  assert.equal(store.get().preferences.bindings.tasks, 'Alt+T')
  await run(`window.shortcutTest.screen('workspace')`); await settle()
  await key('T', ['alt'])
  assert(await run('!document.querySelector(".task-panel-scroll").hidden'), 'Recorded and saved replacement reaches the actual task panel')
  const count = zoomChanges.length
  await key('0', [primary, 'shift'])
  assert.equal(zoomChanges.length, count + 1, 'The reserved combination still reaches the production zoom handler')
  assert.equal(window.webContents.getZoomFactor(), 1)
  assert(await run('!document.querySelector(".task-panel-scroll").hidden'), 'Zoom does not dispatch the task action')
  await key('T', ['alt'])
  await run(`window.shortcutTest.save(${JSON.stringify(defaults)})`); await settle()
  console.log(`Zoom boundary (${platform}): recorded reserved key rejected; replacement saved and triggered; native reset retained`)
}
