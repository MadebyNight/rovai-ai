const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { isAbsolute, join, dirname } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData] = process.argv.slice(2)
assert(isAbsolute(renderer) && isAbsolute(userData))
mkdirSync(userData, { recursive: true })
app.setPath('userData', userData)
app.setPath('sessionData', join(userData, 'session'))
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: process.platform === 'linux', width: 1040, height: 700, useContentSize: true, webPreferences: { contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false } })
  const run = code => window.webContents.executeJavaScript(code, true)
  const settle = () => run('window.navigationTest.settle()')
  const width = () => run('document.querySelector(".unified-sidebar").getBoundingClientRect().width')
  const point = selector => run(`(() => {const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+Math.min(350,r.height/2))}})()`)
  let mousePressed = false
  const mouse = (type, p) => {
    if (type === 'mouseDown') mousePressed = true
    if (type === 'mouseUp') mousePressed = false
    window.webContents.sendInputEvent({ type, ...p, button: 'left', clickCount: 1, modifiers: mousePressed ? ['leftButtonDown'] : [] })
  }
  const key = async (keyCode, modifiers = []) => { window.webContents.sendInputEvent({type:'keyDown',keyCode,modifiers}); window.webContents.sendInputEvent({type:'keyUp',keyCode,modifiers}); await settle() }
  const drag = async (delta, release = true) => { const p=await point('.navigation-resize-handle'); mouse('mouseMove',p); mouse('mouseDown',p); await settle(); const end={...p,x:p.x+delta}; mouse('mouseMove',end); await settle(); if(release) {mouse('mouseUp',end);await settle()} return {start:p,end} }
  const click = async selector => {const p=await point(selector);mouse('mouseMove',p);mouse('mouseDown',p);mouse('mouseUp',p);await settle()}
  const capture = async name => writeFileSync(join(dirname(userData),name+'.png'),(await window.webContents.capturePage()).toPNG())
  try {
    await window.loadFile(renderer); await settle()
    await run(`window.pointerEvents=[];for(const type of ['pointerdown','pointermove','pointerup','gotpointercapture','lostpointercapture','pointercancel'])document.addEventListener(type,e=>window.pointerEvents.push({type,x:e.clientX,buttons:e.buttons,primary:e.isPrimary,target:e.target.className}),true)`)
    assert.equal(await width(),270)
    assert.equal(await run('document.querySelector(".windows-application-menu-item").getBoundingClientRect().left > document.querySelector(".navigation-collapse-button").getBoundingClientRect().right'),true)
    const initialRenders=await run('window.navigationTest.renders()')
    await run('document.querySelector("textarea").value="保留输入草稿"')
    await drag(80)
    assert.equal(await width(),350)
    assert.equal(await run('window.navigationTest.renders()'),initialRenders)
    await click('.navigation-collapse-button');assert.equal(await width(),0)
    assert.equal(await run('document.querySelector("main").getBoundingClientRect().x'),0)
    assert.equal(await run('document.querySelector(".unified-sidebar").inert'),true)
    await capture('windows-collapsed')
    await click('.navigation-collapse-button');assert.equal(await width(),350)
    assert.equal(await run('document.querySelector("textarea").value'),'保留输入草稿')
    await drag(-150);assert.equal(await width(),200)
    const gesture=await drag(-20,false);assert.equal(await width(),0)
    // Reverse one captured gesture back across the threshold, including the starting dead zone.
    mouse('mouseMove',gesture.start);await settle();assert.equal(await width(),200)
    mouse('mouseMove',gesture.end);await settle();assert.equal(await width(),0)
    await key('Escape');mouse('mouseUp',gesture.end);await settle();assert.equal(await width(),200)
    await drag(-20);assert.equal(await width(),0)
    await drag(260);assert.equal(await width(),260)
    await run('document.querySelector(".navigation-resize-handle").focus()')
    await key('Home');assert.equal(await width(),200)
    await key('Left');assert.equal(await width(),0)
    await key('Right');assert.equal(await width(),200)
    await key('End');assert.equal(await width(),420)
    await key('Space');assert.equal(await run('Boolean(document.querySelector("[role=menu]"))'),true)
    await key('Escape')
    await click('.navigation-collapse-button')
    await new Promise(resolve => {window.webContents.once('did-finish-load',resolve);window.reload()});await settle()
    assert.equal(await width(),0)
    await click('.navigation-collapse-button');assert.equal(await width(),420)
    await run('window.navigationTest.setSettings(true)');await settle()
    await click('.navigation-collapse-button');assert.equal(await width(),0)
    await run('window.navigationTest.setPlatform("darwin");document.documentElement.dataset.theme="night"');await settle()
    assert.equal(await run('document.querySelector(".navigation-collapse-button").getBoundingClientRect().x'),82)
    assert.equal(await run('document.querySelector("main").getBoundingClientRect().y >= 50'),true)
    await capture('mac-layout-night-collapsed')
    await run('window.navigationTest.setDisabled(true)');await settle()
    assert.equal(await run('document.querySelector(".navigation-collapse-button").disabled'),true)
    assert.equal(await run('document.querySelector(".navigation-resize-handle").tabIndex'),-1)
    console.log(JSON.stringify({ok:true,checks:'pointer threshold/reversal/cancellation, full collapse/inert, keyboard/menu, storage, unchanged content renders, draft retention, Windows/menu and macOS layout'}))
    window.destroy();app.quit()
  } catch(error) {console.error(error);console.error(await run('JSON.stringify({events:window.pointerEvents?.slice(-30),shell:document.querySelector(".navigation-shell").outerHTML.slice(0,300)})'));await capture('failure');app.exit(1)}
}).catch(error=>{console.error(error);app.exit(1)})
