const assert = require('node:assert/strict')
const { writeFileSync } = require('node:fs')
const { join } = require('node:path')

module.exports = async function verifyLongTextPaste({ evaluate, wait, window, evidence }) {
  const state = () => evaluate('invitationTest.state()')
  const pasteState = () => evaluate('pasteTest.state()')
  const reset = async (pending = false) => {
    await evaluate('invitationTest.hide()')
    await wait('!document.querySelector("#camp-message")')
    await evaluate(`pasteTest.reset(${pending}); invitationTest.show()`)
    await wait('document.querySelector("#camp-message[contenteditable=true]") && invitationTest.state().text === ""')
    await evaluate('invitationTest.focus()')
  }
  const paste = text => evaluate(`pasteTest.paste(${JSON.stringify(text)})`)
  const type = text => window.webContents.debugger.sendCommand('Input.insertText', { text })
  const settle = () => wait('pasteTest.state().preparing === 0')
  const long = '😀'.repeat(10_001)
  const textDocument = text => JSON.stringify({ version: 2, segments: [{ kind: 'text', text }] })

  await reset()
  const boundary = '😀'.repeat(10_000)
  await evaluate(`pasteTest.paste("fallback", ${JSON.stringify(textDocument(boundary))})`)
  assert.equal((await state()).text, boundary, 'Internal text remains authoritative at the threshold')
  assert.equal((await pasteState()).preparedFiles.length, 0)

  // Copy through the production editor: plain text also carries the private MIME.
  await reset()
  const copiedText = ' @爱丽丝 /review-code\t\n' + long + '\n  '
  await type(copiedText)
  await evaluate('pasteTest.selectAll()')
  await new Promise(resolve => setTimeout(resolve, 30))
  const copied = await evaluate(`(() => {
    const data = new DataTransfer()
    document.getElementById('camp-message').dispatchEvent(new ClipboardEvent('copy', {
      clipboardData: data, bubbles: true, cancelable: true
    }))
    return { text: data.getData('text/plain'), structured: data.getData('application/x-rovai-composer+json') }
  })()`)
  assert.equal(copied.text, copiedText)
  assert.ok(JSON.parse(copied.structured).segments.every(segment => segment.kind === 'text'))
  await reset()
  await type('keep selected body')
  await evaluate('pasteTest.selectAll()')
  await new Promise(resolve => setTimeout(resolve, 30))
  await evaluate(`pasteTest.paste(${JSON.stringify(copied.text)}, ${JSON.stringify(copied.structured)})`)
  await wait('invitationTest.state().draft?.attachments.length === 1 && pasteTest.state().preparing === 0')
  assert.equal((await state()).text, 'keep selected body')
  assert.equal((await pasteState()).preparedFiles[0].text, copiedText)
  assert.equal((await pasteState()).preparedFiles[0].size, Buffer.byteLength(copiedText, 'utf8'))

  await reset()
  const splitText = JSON.stringify({ version: 2, segments: [
    { kind: 'text', text: ' \t\r\n' }, { kind: 'text', text: long }, { kind: 'text', text: '\n  ' }
  ] })
  await evaluate(`pasteTest.paste("short fallback", ${JSON.stringify(splitText)})`)
  await wait('invitationTest.state().draft?.attachments.length === 1 && pasteTest.state().preparing === 0')
  assert.equal((await pasteState()).preparedFiles[0].text, ' \t\r\n' + long + '\n  ')

  await reset()
  await paste('😀'.repeat(10_000))
  assert.equal((await state()).text, '😀'.repeat(10_000))
  assert.equal((await pasteState()).preparedFiles.length, 0)

  await reset()
  await paste('a'.repeat(6_000)); await paste('b'.repeat(6_000))
  assert.equal((await state()).text, 'a'.repeat(6_000) + 'b'.repeat(6_000))
  assert.equal((await pasteState()).preparedFiles.length, 0)
  await reset()
  await type(long)
  assert.equal((await state()).text, long)
  assert.equal((await pasteState()).preparedFiles.length, 0)

  await reset()
  await type('existing body')
  await evaluate('pasteTest.selectAll()')
  await new Promise(resolve => setTimeout(resolve, 30))
  const exact = ' \t\r\n' + long + '\n  '
  await paste(exact)
  await wait('invitationTest.state().draft?.attachments.length === 1 && pasteTest.state().preparing === 0')
  assert.equal((await state()).text, 'existing body', 'Attachment conversion must not replace selected text')
  const prepared = (await pasteState()).preparedFiles[0]
  assert.equal(prepared.text, exact)
  assert.equal(prepared.size, Buffer.byteLength(exact, 'utf8'))
  assert.equal(prepared.type, 'text/plain;charset=utf-8')
  assert.equal(prepared.name, '粘贴内容-1.txt')
  for (const theme of ['day', 'night']) {
    await evaluate(`document.documentElement.dataset.theme = '${theme}'`)
    await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
    writeFileSync(join(evidence, `long-paste-${theme}.png`), (await window.webContents.capturePage()).toPNG())
  }
  await evaluate('invitationTest.hide()'); await wait('!document.querySelector("#camp-message")')
  await evaluate('invitationTest.show()')
  await wait('invitationTest.state().text === "existing body" && invitationTest.state().draft?.attachments.length === 1')
  await evaluate('invitationTest.submit()')
  await wait('invitationTest.state().submissions.length === 1')
  assert.equal((await state()).submissions[0].attachments[0].sourcePath, '/fixture/粘贴内容-1.txt')
  assert.equal((await state()).text, 'existing body', 'Rejected send retains the body and attachment')

  await reset()
  for (const name of ['original.txt', 'image.png']) {
    await evaluate(`pasteTest.paste(${JSON.stringify(long)}, undefined, undefined, ${JSON.stringify(name)})`)
  }
  await wait('invitationTest.state().draft?.attachments.length === 2 && pasteTest.state().preparing === 0')
  assert.deepEqual((await pasteState()).preparedFiles.map(file => file.name), ['original.txt', 'image.png'])
  assert.equal((await state()).text, '')
  for (const atom of [
    { type: 'member', agentId: 'lead' },
    { type: 'all_members' },
    { type: 'skill', skillId: 'paste-review', nameAtSend: 'review-code' }
  ]) {
    await reset()
    if (atom.type === 'skill') {
      await type('/')
      await wait('document.querySelector(".structured-skill-menu")?.textContent.includes("review-code")')
      await evaluate('pasteTest.selectAll()')
      await new Promise(resolve => setTimeout(resolve, 30))
    }
    const structured = JSON.stringify({ version: 2, segments: [
      { kind: 'atom', atom }, { kind: 'text', text: long }
    ] })
    await evaluate(`pasteTest.paste(${JSON.stringify(long)}, ${JSON.stringify(structured)})`)
    await wait(`document.querySelectorAll('#camp-message [data-composer-atom="${atom.type}"]').length === 1`)
    assert.equal((await pasteState()).preparedFiles.length, 0)
    assert.ok((await state()).text.endsWith(long))
  }

  await reset()
  await evaluate(`pasteTest.paste(${JSON.stringify(long)}, "invalid")`)
  await wait('invitationTest.state().draft?.attachments.length === 1')
  await evaluate(`pasteTest.paste("", undefined, ${JSON.stringify('<pre>' + long + '</pre>')})`)
  await wait('invitationTest.state().draft?.attachments.length === 2 && pasteTest.state().preparing === 0')
  assert.deepEqual((await pasteState()).preparedFiles.map(file => file.text), [long, long])

  await reset()
  await evaluate('pasteTest.paste("", undefined, undefined, "粘贴内容-1.txt")')
  await evaluate(`pasteTest.paste(${JSON.stringify(long)}); pasteTest.paste(${JSON.stringify(long)})`)
  await wait('invitationTest.state().draft?.attachments.length === 3 && pasteTest.state().preparing === 0')
  assert.deepEqual((await pasteState()).preparedFiles.map(file => file.name), ['粘贴内容-1.txt', '粘贴内容-2.txt', '粘贴内容-3.txt'])

  await reset()
  await evaluate('for (let i=0;i<9;i++) pasteTest.paste("", undefined, undefined, "file-"+i+".txt")')
  await wait('invitationTest.state().draft?.attachments.length === 9 && pasteTest.state().preparing === 0')
  await evaluate(`pasteTest.paste(${JSON.stringify(long)}); pasteTest.paste(${JSON.stringify(long + 'overflow')})`)
  await wait('invitationTest.state().draft?.attachments.length === 10 && pasteTest.state().preparing === 0')
  assert.equal((await pasteState()).preparedFiles.length, 10, 'The queued eleventh attachment is never prepared')
  assert.equal((await state()).text, long + 'overflow')
  assert.equal((await pasteState()).failed, 0)
  assert.equal((await state()).button, false)

  await reset()
  await type('before')
  await evaluate('pasteTest.mode("deferred")')
  await evaluate(`pasteTest.paste("short fallback", ${JSON.stringify(textDocument(long))})`)
  await wait('pasteTest.state().deferred')
  await type(' during')
  await evaluate('invitationTest.submit()')
  assert.equal((await state()).submissions.length, 0, 'Preparing does not remember a deferred send intent')
  await evaluate('pasteTest.release(true)')
  await settle()
  assert.equal((await state()).text, 'before during' + long)
  assert.equal((await pasteState()).failed, 0)
  assert.equal((await state()).button, false)
  assert.equal((await state()).submissions.length, 0)
  await evaluate('invitationTest.submit()')
  await wait('invitationTest.state().submissions.length === 1')
  assert.equal((await state()).submissions[0].body, 'before during' + long)

  await reset()
  await type('leave')
  await evaluate('pasteTest.mode("deferred")')
  await paste(long); await wait('pasteTest.state().deferred')
  await evaluate('window.pasteLeft = false; window.pasteLeaving = invitationTest.leave().then(()=>{window.pasteLeft=true}); true')
  assert.equal(await evaluate('window.pasteLeft'), false)
  await evaluate('pasteTest.release(true)')
  await wait('window.pasteLeft')
  assert.equal((await state()).draft.body, 'leave' + long, 'Leave waits for recovery and persists the appended text')
  await evaluate('pasteTest.otherThread(); invitationTest.show()')
  await wait('document.querySelector("#camp-message[contenteditable=true]")')
  assert.equal((await state()).text, '', 'Recovery cannot append into the next Thread')

  await reset(true)
  await evaluate('pasteTest.failPresence(true)')
  await paste(long)
  await wait('pasteTest.state().preparing === 0 && pasteTest.state().persistenceError?.includes("presence offline")')
  assert.equal((await state()).draft.attachments.length, 1)
  assert.equal((await state()).text, '', 'Already saved attachment must not be appended on presence failure')
  assert.equal((await pasteState()).failed, 0)
  assert.equal(await evaluate('invitationTest.leave().then(() => true, () => false)'), false, 'Attachment-only presence failures still protect leaving')
  await type('typed afterwards')
  await evaluate('pasteTest.failPresence(false)')
  await evaluate('invitationTest.leave()')
  assert.equal((await state()).draft.body, 'typed afterwards')
  assert.equal((await state()).draft.attachments.length, 1)

  await reset(true)
  await evaluate('pasteTest.failStorage(true)')
  await paste(long)
  await wait('pasteTest.state().preparing === 0 && invitationTest.state().text.length > 10000')
  assert.equal((await state()).text, long)
  assert.equal((await state()).draft?.attachments.length ?? 0, 0)
  assert.equal((await pasteState()).failed, 0)
  await evaluate('pasteTest.failStorage(false); invitationTest.leave()')
  await wait('!document.querySelector("#camp-message")')
  assert.equal((await state()).draft.body, long)

  for (const pending of [false, true]) {
    // Attachment-only drafts are meaningful for either creation path.
    await reset(pending)
    const writesBeforePaste = await evaluate('pasteTest.draftWrites()')
    await paste(long)
    await wait('invitationTest.state().draft?.attachments.length === 1 && pasteTest.state().preparing === 0')
    assert.equal((await state()).text, '')
    assert.equal((await state()).button, false)
    assert.equal(await evaluate('pasteTest.draftWrites()'), writesBeforePaste + 1, 'An accepted attachment is saved once')
    await evaluate('document.querySelector(".composer .attachment-remove").click()')
    await wait('invitationTest.state().calls.some(call => call.startsWith("cleanup:"))')
    assert.equal((await state()).draft, null)
    assert.equal((await state()).calls.includes('cleanup-before-save'), false)
    await evaluate('invitationTest.leave()')
    assert.equal((await state()).calls.includes('discard-pending'), pending, 'Empty Active Threads must not be discarded')

    await reset(pending)
    await paste(long)
    await wait('invitationTest.state().draft?.attachments.length === 1 && pasteTest.state().preparing === 0')
    await evaluate('invitationTest.accept(); invitationTest.submit()')
    await wait('invitationTest.state().calls.some(call => call.startsWith("discard:"))')
    assert.equal((await state()).submissions[0].body, '')
    assert.equal((await state()).submissions[0].attachments.length, 1)
    assert.equal((await state()).calls.includes('discard-before-save'), false)
    assert.equal((await state()).calls.some(call => call.startsWith('cleanup:')), false)
    assert.equal((await state()).draft, null)
    // First-send acknowledgement is sufficient even while Pending projection lags.
    await evaluate('invitationTest.leave()')
    assert.equal((await state()).calls.includes('discard-pending'), false)

    await reset(pending)
    await paste(long)
    await wait('invitationTest.state().draft?.attachments.length === 1 && pasteTest.state().preparing === 0')
    await evaluate('pasteTest.failAfterSend(true); invitationTest.accept(); invitationTest.submit()')
    await wait('!!document.querySelector(".composer-draft-load-error")')
    assert.equal((await state()).draft.attachments.length, 1, 'A failed post-send clear keeps the recoverable old draft')
    assert.equal((await state()).calls.some(call => call.startsWith('discard:')), false, 'Do not release its registration')
    assert.equal((await state()).calls.some(call => call.startsWith('cleanup:')), false)
    await evaluate('pasteTest.failStorage(false); document.querySelector(".composer-draft-load-error button").click()')
    await wait('!document.querySelector(".composer-draft-load-error") && document.querySelector("#camp-message[contenteditable=true]")')
    assert.equal((await state()).draft.attachments.length, 1)
  }

  // Keep text so the existing empty-draft reload does not add its own clear.
  await reset()
  await type('keep body')
  await paste(long)
  await wait('invitationTest.state().draft?.attachments.length === 1 && pasteTest.state().preparing === 0')
  const writesBeforeRemoval = await evaluate('pasteTest.draftWrites()')
  await evaluate('document.querySelector(".composer .attachment-remove").click()')
  await wait('invitationTest.state().calls.some(call => call.startsWith("cleanup:"))')
  assert.equal((await state()).draft.body, 'keep body')
  assert.equal(await evaluate('pasteTest.draftWrites()'), writesBeforeRemoval + 1, 'Removal saves its replacement snapshot once')

  // Only the current frozen draft reaches publication, even when cleanup failed.
  await reset()
  await paste(long); await paste(long + 'remaining')
  await wait('invitationTest.state().draft?.attachments.length === 2 && pasteTest.state().preparing === 0')
  const remainingId = (await state()).draft.attachments[1].id
  await evaluate('pasteTest.failCleanup(true); document.querySelector(".composer .attachment-remove").click()')
  await wait('invitationTest.state().draft?.attachments.length === 1 && pasteTest.state().toast?.includes("清理失败")')
  await evaluate('invitationTest.submit()')
  await wait('invitationTest.state().submissions.length === 1')
  assert.deepEqual((await state()).submissions[0].attachments.map(attachment => attachment.id), [remainingId])
  await evaluate('pasteTest.failCleanup(false); document.querySelector(".composer .attachment-remove").click()')
  await wait('!invitationTest.state().draft?.attachments.length')
  await evaluate('invitationTest.focus()')
  await type('text only')
  await evaluate('invitationTest.accept(); invitationTest.submit()')
  await wait('invitationTest.state().submissions.length === 2 && invitationTest.state().draft === null')
  assert.deepEqual((await state()).submissions[1].attachments, [])
  assert.equal((await state()).submissions[1].body, 'text only')
  await evaluate('invitationTest.leave()')
  assert.equal((await state()).calls.includes('discard-pending'), false)

  await reset()
  await type('before')
  await evaluate('pasteTest.mode("deferred")')
  await paste(long)
  await wait('pasteTest.state().deferred')
  await type(' during')
  await evaluate('pasteTest.failStorage(true); pasteTest.release(false)')
  await wait('pasteTest.state().preparing === 0 && invitationTest.state().text.endsWith("😀")')
  assert.equal((await state()).text, 'before during' + long, 'A local acceptance failure cannot load an old body over newer edits')
  assert.equal((await state()).calls.filter(call => call.startsWith('cleanup:')).length, 1)
  assert.equal(await evaluate('invitationTest.leave().then(() => true, () => false)'), false, 'Unsaved fallback uses the existing leave protection')
  assert.equal((await state()).text, 'before during' + long)
  await evaluate('pasteTest.failStorage(false); invitationTest.leave()')
  assert.equal((await state()).draft.body, 'before during' + long)

  await reset()
  await paste(long)
  await wait('invitationTest.state().draft?.attachments.length === 1 && pasteTest.state().preparing === 0')
  await evaluate('pasteTest.failStorage(true); document.querySelector(".composer .attachment-remove").click()')
  await wait('pasteTest.state().persistenceError?.includes("storage full")')
  assert.equal((await state()).calls.some(call => call.startsWith('cleanup:')), false)
  assert.equal((await state()).draft.attachments.length, 1)
  await evaluate('pasteTest.failStorage(false); pasteTest.failCleanup(true); document.querySelector(".composer .attachment-remove").click()')
  await wait('pasteTest.state().toast?.includes("清理失败")')
  assert.equal((await state()).draft, null)
  await evaluate('invitationTest.focus()')
  await type('continue editing')
  await evaluate('invitationTest.leave()')
  assert.equal((await state()).draft.body, 'continue editing', 'Cleanup failure must not block saving or leaving')

  await reset()
  await evaluate('invitationTest.language("en")')
  await paste(long)
  await wait('invitationTest.state().draft?.attachments.length === 1 && pasteTest.state().preparing === 0')
  assert.equal((await pasteState()).preparedFiles[0].name, 'Pasted-text-1.txt')
  await evaluate('invitationTest.language("zh-CN")')

  await reset()
  await evaluate(`window.originalFile = File; window.File = function(){throw new Error("File unavailable")}; pasteTest.paste(${JSON.stringify(long)}); window.File = window.originalFile; true`)
  assert.equal((await state()).text, long)
  assert.equal((await pasteState()).preparedFiles.length, 0)
  assert.deepEqual((await state()).errors, [])
  // Shared production cards: both locales/themes, restore, then the accepted message.
  const cardState = selector => evaluate(`Array.from(document.querySelectorAll(${JSON.stringify(selector)})).map(card => ({
    width: card.getBoundingClientRect().width, height: card.getBoundingClientRect().height,
    title: card.querySelector('strong')?.textContent, label: card.querySelector('small')?.textContent,
    overflow: card.querySelector('strong')?.scrollWidth > card.querySelector('strong')?.clientWidth
  }))`)
  for (const language of ['zh-CN', 'en']) {
    await reset()
    await evaluate(`invitationTest.language('${language}')`)
    await paste('# Rovai：Claude Code、CodeBuddy 原生后台执行限制方案\n' + long)
    for (const name of ['ordinary-file-with-a-very-long-name-that-needs-ellipsis.md', 'short.json']) {
      await evaluate(`pasteTest.paste("", undefined, undefined, ${JSON.stringify(name)})`)
    }
    await wait('invitationTest.state().draft?.attachments.length === 3 && pasteTest.state().preparing === 0')
    await evaluate('invitationTest.hide()'); await wait('!document.querySelector("#camp-message")')
    await evaluate('invitationTest.show()'); await wait('document.querySelectorAll(".composer .attachment-card").length === 3')
    const cards = await cardState('.composer .attachment-card')
    assert.ok(cards.every(card => card.width <= 224.5 && card.height === 48))
    assert.ok(cards[0].title.startsWith('# Rovai：Claude Code'))
    assert.equal(cards[0].label, language === 'en' ? 'Pasted text' : '粘贴内容')
    assert.ok(cards[0].overflow && cards[1].overflow)
    assert.ok(cards[2].width < 224, 'Short filenames stay naturally narrow')
    for (const theme of ['day', 'night']) {
      await evaluate(`document.documentElement.dataset.theme = '${theme}'`)
      await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
      writeFileSync(join(evidence, `compact-cards-${language}-${theme}.png`), (await window.webContents.capturePage()).toPNG())
    }
    await evaluate('invitationTest.accept(); invitationTest.submit()')
    await wait('invitationTest.state().draft === null && document.querySelectorAll(".user-timeline").length === 3')
    const sent = await cardState('.user-timeline')
    assert.ok(sent.every(card => card.width <= 224.5 && card.height === 46))
    assert.equal(sent[0].title, cards[0].title)
    assert.equal(sent[0].label, cards[0].label)
    await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
    writeFileSync(join(evidence, `compact-cards-sent-${language}.png`), (await window.webContents.capturePage()).toPNG())
    await evaluate('pasteTest.agentFiles()')
    await wait('document.querySelectorAll(".agent-timeline").length === 3')
    for (const width of [800, 200]) {
      await evaluate(`document.querySelector('.agent-message-outputs').style.width = '${width}px'`)
      const agentCards = await cardState('.agent-timeline')
      const gridWidth = await evaluate('document.querySelector(".agent-output-file-grid").getBoundingClientRect().width')
      assert.equal(gridWidth, Math.min(620, width), 'Agent files fill available space up to the original 620px limit')
      assert.ok(agentCards.every(card => Math.abs(card.width - (gridWidth - 2)) < 0.5 && card.height >= 56))
      assert.equal(agentCards[0].title, cards[0].title)
      if (width === 200) assert.ok(agentCards[0].overflow && agentCards[1].overflow)
      for (const theme of ['day', 'night']) {
        await evaluate(`document.documentElement.dataset.theme = '${theme}'`)
        await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
        writeFileSync(join(evidence, `agent-cards-${language}-${theme}-${width}.png`), (await window.webContents.capturePage()).toPNG())
      }
    }
    await evaluate('document.querySelector(".agent-message-outputs").style.removeProperty("width")')
    assert.deepEqual((await state()).errors, [])
  }
  await evaluate('invitationTest.language("zh-CN")')
  await reset(true)
  console.error('Long-text paste cases passed: thresholds, Unicode/UTF-8, selection, storage/send, priority, names, capacity, delayed failure, leave, presence and storage failure')
}
