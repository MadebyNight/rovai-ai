const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { isAbsolute, join, dirname } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData] = process.argv.slice(2)
assert(isAbsolute(renderer) && isAbsolute(userData))
mkdirSync(userData, { recursive: true })
app.setPath('userData', userData); app.setPath('sessionData', join(userData, 'session'))
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: process.platform === 'linux', width: 1040, height: 700, useContentSize: true, webPreferences: { contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false, offscreen: process.platform === 'win32' } })
  window.webContents.on('console-message', event => console.error(event.message))
  const run = code => window.webContents.executeJavaScript(code, true)
  const settle = () => run('window.runtimeTest.settle()')
  const click = async selector => {
    const p = await run(`(() => {const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error(${JSON.stringify(selector)});e.scrollIntoView({block:'nearest'});const r=e.getBoundingClientRect();return{x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`)
    const zoom = window.webContents.getZoomFactor(); p.x = Math.round(p.x * zoom); p.y = Math.round(p.y * zoom)
    for (const type of ['mouseMove', 'mouseDown', 'mouseUp']) window.webContents.sendInputEvent({ type, ...p, button: 'left', clickCount: 1 })
    await settle()
  }
  const key = async (keyCode, modifiers = []) => { window.webContents.sendInputEvent({ type: 'keyDown', keyCode, modifiers }); window.webContents.sendInputEvent({ type: 'keyUp', keyCode, modifiers }); await settle() }
  const draft = () => run('window.runtimeTest.draft')
  const search = async text => { await window.webContents.insertText(text); await settle() }
  const capture = async name => writeFileSync(join(dirname(userData), `${name}.png`), (await window.webContents.capturePage(undefined, { stayHidden: true })).toPNG())
  const modelTrigger = '.runtime-model-field .runtime-model-picker-trigger'
  try {
    await window.loadFile(renderer); await settle()
    assert.deepEqual((await draft()).model, { mode: 'runtime_default' })
    assert.equal(await run('window.runtimeTest.calls'), 0)
    await click(modelTrigger)
    assert.equal(await run('document.activeElement.getAttribute("aria-label")'), '搜索模型')
    assert.equal(await run('Boolean(document.querySelector(".runtime-model-picker-heading"))'), false)
    assert.equal(await run('document.querySelector("[role=listbox]").lastElementChild.textContent'), '默认')
    const calls = await run('window.runtimeTest.calls')
    await search('MODEL')
    await run('document.querySelector(".runtime-picker-scroll").scrollTop=1000')
    await search('-')
    assert.equal(await run('(() => {const list=document.querySelector(".runtime-picker-scroll").getBoundingClientRect();const first=document.querySelector(".runtime-picker-scroll [role=option]").getBoundingClientRect();return first.top>=list.top&&first.bottom<=list.bottom})()'),true)
    await run('document.activeElement.select()')
    await search('VENDOR/MODEL-23')
    assert.equal(await run('document.querySelectorAll(".runtime-picker-scroll [role=option]").length'), 1)
    assert.equal(await run('window.runtimeTest.calls'), calls)
    await capture('search-day')
    await run('document.activeElement.dispatchEvent(new CompositionEvent("compositionstart", {bubbles:true}))')
    await key('Enter'); assert.deepEqual((await draft()).model, { mode: 'runtime_default' })
    await run('document.activeElement.dispatchEvent(new CompositionEvent("compositionend", {bubbles:true}))')
    await key('Enter')
    assert.deepEqual((await draft()).model, { mode: 'explicit', modelId: 'vendor/model-23', options: {} })
    assert.equal(await run(`document.activeElement.matches('${modelTrigger}')`), true)
    const reasoning = 'button[aria-label="推理强度，跟随模型默认值"]'
    await click(reasoning)
    assert.equal(await run('document.querySelector("[role=menu]").lastElementChild.lastElementChild.textContent'), '跟随模型默认值')
    await key('Home'); await key('Down'); await key('Enter')
    assert.equal((await draft()).model.options.reasoning_effort, 'high')
    await click('button[aria-label="推理强度，High"]'); await key('End'); await key('Enter')
    assert.deepEqual((await draft()).model.options, {})
    await click(modelTrigger); await search('没有这个模型')
    assert.equal(await run('document.querySelectorAll(".runtime-picker-scroll button[role=option]").length'), 0)
    await capture('empty-search-day')
    await key('Escape'); assert.equal(await run('Boolean(document.querySelector(".runtime-model-search"))'), false)
    await click(modelTrigger)
    assert.equal(await run('document.querySelector("[aria-label=搜索模型]").value'), '')
    await key('Tab'); assert.equal(await run('document.activeElement.getAttribute("aria-label")'), '推理强度，跟随模型默认值')
    await click('button[aria-label="文件系统访问，Safe"]'); await key('End'); await key('Enter')
    assert.equal((await draft()).permissions.values.sandbox_mode, 'full')
    await click('[data-member-runtime-select]'); await key('Escape')
    assert.equal(await run('document.activeElement.hasAttribute("data-member-runtime-select")'), true)
    for (const page of ['member', 'onboarding']) {
      await run(`window.runtimeTest.reset(${JSON.stringify(page)}, 'normal')`); await settle()
      assert.deepEqual((await draft()).model, { mode: 'runtime_default' })
      assert.equal(await run('Boolean(document.querySelector("button[aria-label^=推理强度]"))'), false)
      if (page === 'onboarding') assert.equal(await run('Boolean(document.querySelector("button[aria-label^=文件系统访问]"))'), false)
      await click(modelTrigger); await search('vendor/model-0'); await key('Enter')
      assert.deepEqual((await draft()).model.options, {})
      await click(modelTrigger); await click('.runtime-picker-default [role=option]')
      assert.deepEqual((await draft()).model, { mode: 'runtime_default' })
    }
    await run('window.runtimeTest.reset("member", "failed")'); await settle(); await click(modelTrigger)
    assert.equal(await run('document.querySelector(".runtime-model-picker-notice").textContent.includes("已保留上次结果")'), true)
    await key('Escape')
    await run('window.runtimeTest.reset("onboarding", "empty")'); await settle(); await click(modelTrigger)
    assert.equal(await run('document.querySelector(".runtime-picker-default [role=option]").disabled'), false)
    await click('.runtime-picker-default [role=option]')
    await run('window.runtimeTest.reset("member", "pending")'); await settle(); await click(modelTrigger)
    assert.equal(await run('document.querySelector(".runtime-model-picker-empty").textContent'), '正在获取模型列表…')
    await click('.runtime-picker-default [role=option]')
    const beforeSwitch = await run('window.runtimeTest.calls')
    await run('window.runtimeTest.switchKind("claude-code-cli")'); await settle()
    assert.equal(await run('window.runtimeTest.calls'), beforeSwitch)
    await run('window.runtimeTest.pending.shift()()'); await settle()
    assert.deepEqual((await draft()).model, { mode: 'runtime_default' })
    await run('window.runtimeTest.reset("member", "normal")'); await settle()
    for (const [width, height, zoom] of [[1040,700,1], [1440,920,1], [2560,1440,1], [1040,700,2]]) {
      window.setContentSize(width,height); window.webContents.setZoomFactor(zoom); await settle()
      await click(modelTrigger)
      assert.equal(await run('(() => {const r=document.querySelector(".runtime-model-search-menu").getBoundingClientRect();const d=document.querySelector(".runtime-picker-default").getBoundingClientRect();return r.x>=0&&r.right<=innerWidth&&r.y>=0&&r.bottom<=innerHeight&&d.bottom<=r.bottom})()'), true)
      assert.equal(await run('document.documentElement.scrollWidth <= innerWidth'), true)
      await capture(`size-${width}-${zoom}`); await key('Escape')
    }
    window.webContents.setZoomFactor(1); window.setContentSize(1440,920)
    await run('document.documentElement.dataset.theme="night"'); await settle(); await click(modelTrigger); await capture('models-night'); await key('Escape')
    await run('window.runtimeTest.setDisabled(true)'); await settle()
    assert.equal(await run(`document.querySelector('${modelTrigger}').disabled`), true)
    console.log(JSON.stringify({ ok:true, checks:'default policy and effort, both entry points, search by ID/case, no discovery on typing/switch, IME, keyboard/Escape/Tab, fixed default, failure/empty/pending, late catalog, disabled, Day/Night, 1040/1440/2560 and 200% zoom' }))
    window.destroy(); app.quit()
  } catch (error) { console.error(error); await capture('failure'); app.exit(1) }
}).catch(error => { console.error(error); app.exit(1) })
